"""Freeze a reviewable private verifier clone; no compiler/checker execution."""
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[5]
HERE = Path(__file__).resolve().parent
SOURCE = ROOT / 'selfhost/build/phase143/integrated-source03/compiler.bend'
EXPECTED = 'a51a4a6d0a32e118ca75eac96fb4e64bae0fcf951b09ee859c2632f65550bd4e'


def pin(p):
    b = p.read_bytes()
    return dict(file=str(p), bytes=len(b), sha256=hashlib.sha256(b).hexdigest())


assert pin(SOURCE)['sha256'] == EXPECTED
source = SOURCE.read_text()
start = source.index('type P111VScan is Data:')
end = source.index('# Phase111 module: selfhost/tools/performance/phase111/qbe/numbers.bend', start)
original = source[start:end]
body = original
body = body.replace('p111_verify_program', 'p144v_verify_program').replace('p111v_', 'p144v_')
body = body.replace('P111VScan', 'P144VScan').replace('P111VFlow', 'P144VFlow')
body = body.replace('N111Ids', 'P144VIds').replace('KDef', 'P144VTree')
body = body.replace('KIndexLeaf', 'P144VTLeaf').replace('KIndexNode', 'P144VTNode')
for old, new in [('dn', 'p144vt_name'), ('dk', 'p144vt_kind'), ('da', 'p144vt_width'), ('dx', 'p144vt_capacity')]:
    body = re.sub(r'\b' + old + r'\(', new + '(', body)
body = body.replace('missing()', 'P144VTEmpty{}')
old = '''def p144v_get(+tree: P144VTree, +name: String) -> P144VTree:
  index_find(tree,name,index_hash(name,2166136261),32)'''
new = '''def p144v_get(+tree: P144VTree, +name: String) -> P144VEntry:
  p144vt_find(tree,name,index_hash(name,2166136261))'''
assert body.count(old) == 1
body = body.replace(old, new)
old = '  index_set(tree,P144VTree{name,kind,width,capacity,atom("Absent"),atom("Absent"),[],False{},False{}},index_hash(name,2166136261),32)'
new = '  p144vt_insert(tree,P144VEntry{name,kind,width,capacity},index_hash(name,2166136261))'
assert body.count(old) == 1
body = body.replace(old, new)
body = body.replace('+bucket: List<&2,P144VTree>', '+bucket: List<&2,P144VEntry>')
# Target references return metadata entries, not local maps. Their wrong-kind
# branches are absent entries just like dk(missing())/da/dx in the reference.
a = body.index('def p144v_target(')
b = body.index('@unsafe', a)
target = body[a:b].replace('-> P144VTree:', '-> P144VEntry:').replace('nt_choose(P144VTree,', 'nt_choose(P144VEntry,').replace('P144VTEmpty{}', 'p144vt_absent()')
body = body[:a] + target + body[b:]
assert not re.search(r'\b(?:KDef|index_find|index_set|dn|dk|da|dx|N111Ids|p111v_\w+)\b', body)
header = '# Mechanically extracted private representation ablation.\n# Generated by extract-v03.py from the pinned selected compiler.\n# Original protected verifier remains unmodified and independent.\n\n'
destination = HERE / 'verifier-v03.bend'
assert not destination.exists(), destination
destination.write_text(header + body)
manifest = dict(kind='phase144-private-typed-verifier-source-bridge', complete=True,
    checked=False, source=pin(SOURCE), method=pin(Path(__file__).resolve()),
    table=pin(HERE/'table-v03.bend'), clone=pin(destination),
    originalDeclarations=re.findall(r'^def (\w+)\(', original, flags=re.M),
    sourceLines=len(body.splitlines()),
    scope='All original raw-verifier decisions/error strings retained under name/type/getter substitution. Private canonical Patricia table uses four-field rows. No proof, independent type check, target execution, performance claim or production override.')
(HERE/'source-bridge-v03.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps(dict(clone=manifest['clone'],lines=manifest['sourceLines'])))
