import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {spawnSync} from 'node:child_process';
const root=path.resolve(import.meta.dirname,'../../../..');
const args=process.argv.slice(2);assert.equal(args.length,4,'Expected BUILD_DIR CONTROLS_JSON EQUIVALENCE_JSON RELEASE_DIR');
const [build,controlsFile,equivalenceFile]=args.slice(0,3).map(p=>fs.realpathSync(p)),release=path.resolve(args[3]);
const stage=path.join(build,'package'),seen=new Map();
const pin=p=>{p=fs.realpathSync(p);const b=fs.readFileSync(p);return {file:p,bytes:b.length,sha256:createHash('sha256').update(b).digest('hex')};};
const same=(a,b)=>assert.deepEqual([a.sha256,a.bytes],[b.sha256,b.bytes]);
const verify=p=>{const q=pin(p.file);assert.deepEqual(q,{file:p.file,bytes:p.bytes,sha256:p.sha256});if(p.mode!==undefined)assert.equal(fs.statSync(p.file).mode&0o777,p.mode);seen.set(q.file,q);return q.file;};
const json=p=>JSON.parse(fs.readFileSync(p,'utf8'));
const load=p=>{const id=pin(p);verify(id);return [json(p),id];};
const readPin=p=>json(verify(p));
const save=(p,x)=>fs.writeFileSync(p,JSON.stringify(x,null,2)+'\n',{flag:'wx',mode:0o644});
const method=pin(import.meta.filename),host=pin(process.execPath);
assert.equal(host.file,fs.realpathSync(root+'/selfhost/.bootstrap/bun-1.4.3/bun'));
assert.equal(host.sha256,'7ce7d6b654eddeec20afddf2396317fba6dc19ab52788a27e894e1806bf8f24b');
verify(host);
const [inputs,inputsPin]=load(build+'/inputs.json'),[native,nativePin]=load(build+'/native.json');
const [bridge,bridgePin]=load(build+'/bridge.json'),[controls,controlsPin]=load(controlsFile),[equivalence,equivalencePin]=load(equivalenceFile);
assert.equal(inputs.version,1);
for(const p of [...inputs.methods,inputs.source,inputs.compiler,inputs.bridge,inputs.harness,inputs.host,...Object.values(inputs.assets)])verify(p);
const methods=new Map(inputs.methods.map(p=>[path.basename(p.file),p]));
const names=['native-cli.bend','native-os.c','start.c','build.mjs','acquire.mjs'];
assert.deepEqual([...methods.keys()].sort(),[...names].sort());assert.deepEqual(methods.get('native-os.c'),inputs.host);
const baseline=readPin(inputs.baseline);assert(baseline.complete&&baseline.qualified);
assert.equal(baseline.kind,'phase98-native-candidate-qualification');assert.equal(inputs.source.sha256,'63ef222c4c6de73bb54c8e51d3b0a0552979b5791ea98e64d1098051a9cda237');
assert.deepEqual(inputs.source,baseline.source);assert.deepEqual(inputs.cache,baseline.assets.cache);
assert.equal(inputs.baseIdentity,baseline.assets.cacheBasePath);
const assets={'base.bend':baseline.assets.base,'base.p88':baseline.assets.cache.carrier};
baseline.assets.parts.forEach((p,i)=>assets['runtime.c.part'+i]=p);
baseline.assets.effects.forEach(p=>assets['effs/'+path.basename(p.file)]=p);
assert.equal(Object.keys(assets).length,16);assert.deepEqual(inputs.assets,assets);
for(const [name,p] of Object.entries(assets))same(pin(build+'/assets/'+name),p);
same(pin(build+'/native-os.c'),inputs.host);same(pin(build+'/assets/effs/native-os.c'),inputs.host);
assert(native.complete&&native.generatedCUnmodified&&native.stage==='native Bend-produced B2');
assert.deepEqual(native.source,inputs.compiler);assert.deepEqual(native.startup,methods.get('start.c'));
for(const p of [native.binary,native.toolchain,native.startup,bridge.binary,bridge.toolchain])verify(p);
assert.deepEqual(native.binary,pin(build+'/bend'));assert(fs.statSync(native.binary.file).mode&0o111);
assert(bridge.complete);assert.deepEqual(bridge.source,inputs.bridge);assert.deepEqual(bridge.toolchain,native.toolchain);
const acquisition=readPin(bridge.acquisition);
assert(acquisition.complete&&acquisition.holes===0);assert.deepEqual(acquisition.source,inputs.bridge);
assert.deepEqual(acquisition.method,methods.get('acquire.mjs'));
for(const p of [acquisition.source,acquisition.method,acquisition.host,acquisition.c,...acquisition.loadedFiles,...acquisition.upstream.inputs])verify(p);
const emission=readPin(native.emission);assert.deepEqual(native.emission,pin(build+'/emission.json'));
assert(emission.complete&&emission.observers&&emission.packedConstructors&&emission.scalarArrays===false);
assert.deepEqual(emission.source,inputs.compiler);assert.deepEqual(emission.producer,bridge.binary);verify(emission.c);
assert.deepEqual(emission.c,pin(build+'/image.1.c'));
function guard(record,required){const p=readPin(record);assert(p.complete&&p.returncode===0&&!p.stoppedFor&&!p.interrupted);for(const a of required)assert(p.command.includes(a),'Missing build argument: '+a);return p;}
guard(bridge.build,[bridge.toolchain.file,acquisition.c.file,'-O2','-o',bridge.binary.file]);
guard(emission.execution,[bridge.binary.file,inputs.compiler.file,inputs.baseIdentity,inputs.cache.carrier.file,inputs.cache.stamp]);
guard(native.build,[native.toolchain.file,'-O2','-DBEND_NATIVE_HOST=1','-DBEND_IMAGE_C='+JSON.stringify(emission.c.file),native.startup.file,'-o',native.binary.file]);
assert.equal(controls.kind,'phase103-native-cli-controls');assert.equal(controls.mode,'compiler');
assert(controls.complete&&controls.passed&&controls.originalPackageUnchanged&&controls.relocatedAssetsRestored);
assert(controls.rows.length&&controls.rows.every(r=>r.passed&&r.status===r.expectedStatus&&!r.signal&&!r.error));
verify(controls.method);verify(controls.executable);same(controls.executable,native.binary);
for(const p of controls.originalInputs)verify(p);
const controlled=p=>controls.originalInputs.find(q=>q.file===path.join(controls.package,p));
same(controlled('bend'),native.binary);for(const [name,p] of Object.entries(assets))same(controlled('assets/'+name),p);
assert.equal(equivalence.kind,'phase103-native-cli-equivalence');assert(equivalence.complete&&equivalence.passed);
verify(equivalence.method);verify(equivalence.candidate.binary);verify(equivalence.candidate.source);
assert.deepEqual(equivalence.candidate.binary,native.binary);assert.deepEqual(equivalence.candidate.source,inputs.compiler);
assert.deepEqual(equivalence.baseline.admission,inputs.baseline);assert.deepEqual(equivalence.baseline.binary,baseline.stages.b2.binary);verify(equivalence.baseline.binary);
assert(equivalence.rows.length&&equivalence.rows.every(r=>r.cEqual&&r.diagnosticsEqual));
