// All qualification checks precede any staging or release writes. mkdir refuses existing paths, including symlinks.
assert(!fs.existsSync(stage)&&!fs.existsSync(release),'Use fresh package staging and RELEASE_DIR');
fs.mkdirSync(stage);fs.mkdirSync(release);fs.chmodSync(stage,0o755);fs.chmodSync(release,0o755);
const files=[];
function copy(record,name,dir=stage){
  assert(!path.isAbsolute(name)&&!name.split('/').includes('..')&&!/[\r\n\\]/.test(name));
  const target=path.join(dir,name);fs.mkdirSync(path.dirname(target),{recursive:true,mode:0o755});
  fs.copyFileSync(verify(record),target,fs.constants.COPYFILE_EXCL);fs.chmodSync(target,name==='bend'?0o755:0o644);
  const p=pin(target);same(p,record);if(dir===stage)files.push({file:name,bytes:p.bytes,sha256:p.sha256,mode:fs.statSync(target).mode&0o777});
}
copy(native.binary,'bend');for(const [name,p] of Object.entries(assets))copy(p,'assets/'+name);
copy(inputs.compiler,'source/compiler.bend');copy(inputs.bridge,'source/bridge.bend');
for(const name of names)copy(methods.get(name),'source/'+name);
const scope='Native B2 CLI integration with the Phase102 candidate04 compiler core retained; finite CLI/equivalence evidence, not a new fixed-point or full compiler requalification.';
const metadata={kind:'phase103-native-cli-package-build',version:1,scope,method,inputs,native,bridge,emission,qualification:{controls:controlsPin,equivalence:equivalencePin}};
save(stage+'/BUILD.json',metadata);
const recordFile=name=>{const p=pin(stage+'/'+name);files.push({...p,file:name,mode:0o644});};recordFile('BUILD.json');
files.sort((a,b)=>a.file<b.file?-1:a.file>b.file?1:0);
fs.writeFileSync(stage+'/FILES.sha256',files.map(p=>p.sha256+'  '+p.file+'\n').join(''),{flag:'wx',mode:0o644});recordFile('FILES.sha256');
// Normalise directory/file modes independently of the caller's umask.
function modes(dir){fs.chmodSync(dir,0o755);for(const e of fs.readdirSync(dir,{withFileTypes:true})){const p=path.join(dir,e.name);if(e.isDirectory())modes(p);else fs.chmodSync(p,p===stage+'/bend'?0o755:0o644);}}modes(stage);
const records=[['inputs.json',inputsPin],['native.json',nativePin],['bridge.json',bridgePin],['emission.json',native.emission],['controls.json',controlsPin],['equivalence.json',equivalencePin],['bridge-acquisition.json',bridge.acquisition],['bridge-build.json',bridge.build],['native-emission.json',emission.execution],['native-build.json',native.build]];
const retained=[];for(const [name,p] of records)if(p.bytes<=1024**2){copy(p,'records/'+name,release);retained.push({file:'records/'+name,sha256:p.sha256,bytes:p.bytes});}
for(const p of seen.values())verify(p);verify(method);
const tar=pin('/usr/bin/tar'),gzip=pin('/usr/bin/gzip'),archive=release+'/package.tar.gz';
