import api from '../../../build/js-backend.mjs';
import assert from 'node:assert/strict';
const list=xs=>xs.reduceRight((tail,head)=>({$:'Con',head,tail}),{$:'Nil'});
const t=(tag,name='',kids=[],id=0,quant=0)=>({$:'KTerm',tag,name,id,quant,kids:list(kids),removed:list([])});
const all=(name,id,a,b,q=1)=>t('All',name,[a,b],id,q);
const def=(name,value,typ,arity=0,native=false)=>({$:'KDef',name,kind:'Def',arity,templates:0,typ,value,ctors:list([]),native,unsafe:false});
const type=t('Typ','',[t('Qua','',[],0,1)]),u32=t('ADT','U32'),a=t('Var','A',[],1);
const church=all('R',2,type,all('k',3,all('x',4,a,t('ADT','IO.OP')),t('ADT','IO.OP')),0);
const io=def('IO',t('Lam','A',[church],1,0),all('A',1,type,type,0),1,true);
const scalar={...def('U32',t('Absent'),type),kind:'ADT'};
const actual=t('App','',[t('Ref','IO'),u32]);
const base=[io,scalar];
assert.equal(api.j_compile_error(list([])),'a build needs import Base');
assert.equal(api.j_compile_error(list(base)),'no main to run');
assert.equal(api.j_io_type(list(base),actual),true);
assert.equal(api.j_io_type(list(base),church),false);
assert.equal(api.j_io_type(list([{...io,native:false},scalar]),actual),false);
const alias=def('Action',actual,type);
assert.equal(api.j_io_type(list([...base,alias]),t('Ref','Action')),true);
const cached=api.book_cached(list([...base,alias]),40);
assert.equal(api.j_io_type(cached,t('Ref','Action')),true);
assert.equal(api.j_io_type(cached,church),false);
assert.equal(api.j_compile_error(list([...base,def('main',t('Ctr','U32'),u32)])),'');
assert.match(api.j_compile_error(list([...base,def('main',t('Lam','x',[t('Var','x',[],9)],9),all('x',9,u32,u32))])),/cannot be printed/);
assert.equal(api.j_compile_error(list([...base,def('main',t('Foreign','main',[t('Path','x.js')]),actual)])),'main must be a filled def: a foreign main cannot anchor IO');
console.log('entry validation/Base provenance/cached IO alias identity/foreign main passed');
