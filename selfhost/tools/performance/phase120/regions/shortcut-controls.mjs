// Pure reflected admission/selection controls; no host lowering or native run.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import {pathToFileURL} from 'node:url';
const [apiFile,outFile]=process.argv.slice(2);
if(!apiFile||!outFile||process.argv.length!==4||fs.existsSync(outFile))throw Error('Usage: shortcut-controls.mjs CHECKED_API FRESH_REPORT');
const pin=p=>{p=path.resolve(p);const b=fs.readFileSync(p);return {file:p,bytes:b.length,sha256:crypto.createHash('sha256').update(b).digest('hex')};};
const receiptFile=path.join(path.dirname(apiFile),'report.json');
const receipt=JSON.parse(fs.readFileSync(receiptFile));
if(!receipt.complete||!receipt.checked||receipt.api.sha256!==pin(apiFile).sha256)throw Error('Checked API required');
for(const x of [receipt.api,...receipt.inputs]){const y=pin(x.file);if(y.sha256!==x.sha256||y.bytes!==x.bytes)throw Error('Changed input '+x.file);}
const exports=['p120nr_eligible','p120nr_arithmetic','p120nr_prefix_work','p120nr_profit','p120nr_table','p120nr_scan','p120nr_function','p120nr_boundary'];
for(const x of exports)if(!receipt.exports.includes(x))throw Error('Missing export '+x);
const api=(await import(pathToFileURL(path.resolve(apiFile)))).default;
const tag=($,fields={})=>({$,...fields}), list=xs=>xs.reduceRight((tail,head)=>tag('Con',{head,tail}),tag('Nil'));
const arr=xs=>{const a=[];for(;xs.$==='Con';xs=xs.tail)a.push(xs.head);if(xs.$!=='Nil')throw Error('list');return a;};
const U64=tag('N111U64'),U32=tag('N111U32'),Ptr=tag('N111Ptr'),local=name=>tag('N111Local',{name}),con=lo=>tag('N111Const',{lo,hi:0});
const arg=(typ,value)=>tag('N111Arg',{typ,value}),scalar=stmt=>tag('P113DScalar',{stmt});
const store=(offset,value)=>scalar(tag('N111Store',{typ:U64,base:local('scratch'),offset,value}));
const op=(id,count=2,symbol='p111_rt_op')=>scalar(tag('N111Call',{name:'value',typ:U64,symbol,args:list([arg(Ptr,local('state')),arg(U32,con(id)),arg(Ptr,local('scratch')),arg(U32,con(count))])}));
const result=()=>tag('P113DResult',{values:list([local('value')])});
const params=list(['a','b'].map(word=>tag('NC_Binding',{id:0,word,kind:tag('N_W32')})));
const groups=(n,id=26)=>Array.from({length:n},()=>[store(0,local('a')),store(8,local('b')),op(id)]).flat();
const fn=(body,name='$direct.numeric')=>tag('P113DFunction',{name,params,result:1,public:tag('True'),body:list(body)});
const leaf=n=>fn([...groups(n),result()]);
const branch=(yes,no)=>tag('P113DIf',{condition:con(1),yes:list(yes),no:list(no)});
const truth=x=>x===true||x?.$==='True';
const profit=f=>truth(api.p120nr_profit(f));
const eligible=f=>truth(api.p120nr_eligible(f));
const call=target=>tag('P113DCall',{destinations:list(['out']),target,args:list([local('b'),local('a')])});
const table=f=>api.p120nr_table(list([f]),tag('P113IEmpty'));
const rows=[];function check(name,condition){rows.push({name,pass:!!condition});if(!condition)throw Error(name);}
let complete=false,error=null;
try{
 check('one-op-safe-but-unselected',eligible(leaf(1))&&!profit(leaf(1)));
 check('three-op-safe-but-unselected',eligible(leaf(3))&&!profit(leaf(3)));
 check('four-op-safe-and-selected',eligible(leaf(4))&&profit(leaf(4)));
 check('five-op-safe-and-selected',eligible(leaf(5))&&profit(leaf(5)));
 check('all-four-arithmetic-ids-count',profit(fn([...groups(1,26),...groups(1,27),...groups(1,28),...groups(1,29),result()])));
 check('comparisons-do-not-count',!profit(fn([...groups(4,30),result()])));
 check('conversion-does-not-count',!profit(fn([op(23,1),op(23,1),op(23,1),op(23,1),result()])));
 check('sqrt-does-not-count',!profit(fn([op(36,1),op(36,1),op(36,1),op(36,1),result()])));
 const inner=[...groups(4),result()];
 check('branch-only-work-safe-but-unselected',eligible(fn([branch(inner,inner)]))&&!profit(fn([branch(inner,inner)])));
 check('three-before-branch-not-enough',!profit(fn([...groups(3),branch(inner,inner)])));
 check('four-before-branch-selected',eligible(fn([...groups(4),branch([result()],[result()])]))&&profit(fn([...groups(4),branch([result()],[result()])])));
 check('no-count-across-join',!profit(fn([...groups(2),branch([],[]),...groups(2),result()])));
 const ctor=scalar(tag('N111Set',{name:'cid',typ:U64,value:tag('N111CtorId',{name:'Plain'})}));
 check('ctor-id-does-not-block-prefix',eligible(fn([ctor,...groups(4),result()]))&&profit(fn([ctor,...groups(4),result()])));
 const unsafe=scalar(tag('N111Call',{name:'kept',typ:U64,symbol:'p111_rt_keep',args:list([arg(Ptr,local('state')),arg(U64,local('a'))])}));
 const unsafeFn=fn([unsafe,...groups(4),result()]);
 check('profit-is-not-semantic-admission',profit(unsafeFn)&&!eligible(unsafeFn));
 check('unsafe-profitable-never-in-table',api.p120nr_scan(list([call(unsafeFn.name)]),table(unsafeFn),0,1024).next===0);
 check('wrong-arity-not-counted',!truth(api.p120nr_arithmetic(op(26,1).stmt)));
 check('wrong-symbol-not-counted',!truth(api.p120nr_arithmetic(op(26,2,'other').stmt)));
 check('unselected-call-preserved',api.p120nr_scan(list([call(leaf(1).name)]),table(leaf(1)),0,1024).next===0);
 const chosen=leaf(4),expanded=api.p120nr_scan(list([call(chosen.name)]),table(chosen),0,1024),items=arr(expanded.body);
 check('selected-call-copied',expanded.next===1&&!items.some(x=>x.$==='P113DCall'));
 const bindings=items.filter(x=>x.$==='P113DScalar'&&x.stmt.$==='N111Set');
 check('selected-argument-permutation-preserved',bindings[0].stmt.value.name==='b'&&bindings[1].stmt.value.name==='a');
 const capped=api.p120nr_scan(list(Array.from({length:5},()=>call(chosen.name))),table(chosen),0,1024);
 check('four-site-limit-unchanged',capped.next===4&&arr(capped.body).filter(x=>x.$==='P113DCall').length===1);
 check('zero-growth-budget-fallback',api.p120nr_scan(list([call(chosen.name)]),table(chosen),0,0).next===0);
 const renamed=fn([...groups(4),result()],'unrelated.name');
 check('selection-independent-of-function-name',profit(renamed)&&api.p120nr_scan(list([call(renamed.name)]),table(renamed),0,1024).next===1);
 const inert=fn([scalar(tag('N111Bin',{name:'sum',typ:U64,op:'add',left:con(1),right:con(2)})),tag('P113DResult',{values:list([local('sum')])})],'$direct.inert');
 check('zero-copy-retains-exact-body-with-empty-table',JSON.stringify(api.p120nr_function(inert,tag('P113IEmpty')))===JSON.stringify(inert));
 check('zero-copy-retains-exact-body-with-nonempty-table',JSON.stringify(api.p120nr_function(inert,table(chosen)))===JSON.stringify(inert));
 const caller=fn([call(chosen.name),tag('P113DResult',{values:list([local('out')])})],'$direct.caller');
 const rewritten=api.p120nr_function(caller,table(chosen));
 check('copied-body-still-transformed',!arr(rewritten.body).some(x=>x.$==='P113DCall')&&JSON.stringify(rewritten).includes('p120nr_0_'));
 // Local identity test only: raw boundary data is not an admission certificate.
 const emptyProgram=tag('P111Program',{segments:list([]),constructors:list([]),show:list([]),show_names:list([]),effects:list([]),pure:tag('True')});
 const absent=tag('KTerm',{tag:'Absent',name:'',id:0,quant:0,kids:list([]),removed:list([]),originBegin:0,originEnd:0});
 const missing=tag('KDef',{name:'',kind:'Absent',arity:0,templates:0,typ:absent,value:absent,ctors:list([]),native:tag('False'),unsafe:tag('False')});
 const emptyIds=tag('N111Ids',{functions:missing,constructors:missing});
 const boundary=tag('P114SBoundary',{original:tag('P112StaticProgram',{program:emptyProgram,nodes:list([])}),ids:emptyIds,functions:list([inert]),valid:tag('True')});
 check('empty-table-retains-exact-boundary',JSON.stringify(api.p120nr_boundary(boundary))===JSON.stringify(boundary));
 complete=true;
}catch(e){error=String(e);}
fs.mkdirSync(path.dirname(outFile),{recursive:true});
fs.writeFileSync(outFile,JSON.stringify({kind:'phase120-numeric-region-shortcut-controls',complete,inputs:[pin(receiptFile),pin(apiFile),pin(import.meta.filename)],cases:rows,error,scope:'Reflected distinction between semantic eligibility and fixed profit selection; no host compiler transformation and no malformed native execution.'},null,2)+'\n');
if(!complete)throw Error(error);
