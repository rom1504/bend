#!/usr/bin/env python3
"""Prepare cached effect source and its provenance catalogue. No targets run."""
import argparse
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[6]
CID = re.compile(r"CID\(([A-Za-z_][A-Za-z0-9_.]*)\)")
TOKEN = re.compile(r"\bCID_[A-Z0-9_]+\b")
REG = re.compile(r"io_eff\(\s*(CID\([A-Za-z_][A-Za-z0-9_.]*\)|CID_[A-Z0-9_]+)\s*,\s*([A-Za-z_][A-Za-z0-9_]*)\s*(?:,\s*([A-Za-z0-9_]+)\s*)?\);")
INIT = re.compile(r"static void __attribute__\(\(constructor\)\) ([A-Za-z_][A-Za-z0-9_]*)\(void\)")


def pin(path):
    path = Path(path).resolve()
    data = path.read_bytes()
    return dict(file=str(path), bytes=len(data), sha256=hashlib.sha256(data).hexdigest())


def verify(record):
    actual = pin(record['file'])
    if any(actual[k] != record[k] for k in ('bytes', 'sha256')):
        raise ValueError('changed source pin: ' + record['file'])
    return Path(actual['file'])


def macro(name):
    return 'CID_' + re.sub(r'[^A-Za-z0-9_]', '_', name).upper()


def describe(path, names):
    text = path.read_text()
    def semantic(token):
        if token.startswith('CID('):
            return CID.fullmatch(token).group(1)
        if token not in names:
            raise ValueError('unresolved provider CID: ' + token)
        return names[token]
    refs = sorted({*CID.findall(text), *(semantic(t) for t in TOKEN.findall(text))})
    registrations = [dict(name=semantic(m[1]), run=m[2], need=m[3] or '0') for m in REG.finditer(text)]
    return dict(**pin(path), cidNames=refs, registrations=registrations,
                startupFunctions=INIT.findall(text), fidNames=re.findall(r'FID\(([^)]+)\)', text))


def transform(text, names, slots):
    def semantic(token):
        return CID.fullmatch(token).group(1) if token.startswith('CID(') else names[token]
    # The cache contains every selected implementation, independently of which
    # program requests it. Registration, not C preprocessing, chooses live rows.
    text = re.sub(r'(?m)^#ifdef\s+(CID_[A-Z0-9_]+)\s*$', '#if 1', text)
    text = re.sub(r'defined\((CID_[A-Z0-9_]+)\)', '1', text)
    def registration(m):
        slot = slots[semantic(m[1])]
        return ('if (p111_effect_cids[%d] != UINT32_MAX)\n'
                '    io_eff(p111_effect_cids[%d], %s, %s);') % (slot, slot, m[2], m[3] or '0')
    text = REG.sub(registration, text)
    text = INIT.sub(r'static void \1(void)', text)
    text = CID.sub(lambda m: 'p111_effect_cids[%d]' % slots[m[1]], text)
    text = TOKEN.sub(lambda m: 'p111_effect_cids[%d]' % slots[names[m[0]]], text)
    if '((constructor))' in text or CID.search(text) or TOKEN.search(text):
        raise ValueError('untranslated provider syntax')
    return text


def prepare(out, profile):
    selection_path = ROOT / 'selfhost/tools/native/selection.json'
    selection = json.loads(selection_path.read_text())
    admission_path = verify(selection['admission'])
    admission = json.loads(admission_path.read_text())
    if not selection.get('complete') or not admission.get('complete') or not admission.get('qualified'):
        raise ValueError('selected native admission is incomplete')
    assets = admission['assets']
    verify(assets['base'])
    verify(assets['runtime'])
    upstream = Path(assets['base']['file']).parent / 'effs'
    admitted = {str(Path(p['file']).resolve()): p for p in admission['inputs']}
    raw = sorted(upstream.glob('*.c'))
    names = {}
    for path in raw:
        verify(admitted[str(path.resolve())])
        for name in CID.findall(path.read_text()):
            key = macro(name)
            if key in names and names[key] != name:
                raise ValueError('CID spelling collision: ' + key)
            names[key] = name
    host = ROOT / 'selfhost/src/host/native-os.c'
    for name in CID.findall(host.read_text()):
        names[macro(name)] = name
    selected = [verify(p) for p in assets['effects']]
    compiler = {'args.c', 'print.c', 'print_err.c'}
    providers = [p for p in selected if profile == 'selected-base' or p.name in compiler] + [host]
    rows = [describe(p, names) for p in providers]
    all_names = sorted({name for row in rows for name in row['cidNames']})
    slots = {name: i for i, name in enumerate(all_names)}
    effects = [r for row in rows for r in row['registrations']]
    if len({r['name'] for r in effects}) != len(effects):
        raise ValueError('duplicate effect registration')
    starts = [fn for row in rows for fn in row['startupFunctions']]
    if len(set(starts)) != len(starts):
        raise ValueError('duplicate registration initializer')
    parts = [
        '/* Generated by phase111/runtime/effects/prepare.py; include once at Requests. */\n',
        '/* IDs are installed after the descriptor; no .init_array registration. */\n',
        'static uint32_t p111_effect_cids[%d];\n' % len(all_names),
        'static int p111_effects_bound;\n',
    ]
    for row in rows:
        parts += ['\n/* ' + row['file'] + ' SHA256 ' + row['sha256'] + ' */\n',
                  transform(Path(row['file']).read_text(), names, slots)]
    parts += ['\nstatic void p111_effects_bind(uint32_t (*lookup)(void *, const char *), void *context) {\n',
              '  if (lookup == NULL || p111_effects_bound) err_fail("phase111: invalid effect binding lifecycle");\n',
              '  uint32_t ids[%d];\n' % len(all_names)]
    for name, slot in slots.items():
        parts += ['  ids[%d] = lookup(context, %s);\n' % (slot, json.dumps(name)),
                  '  if (ids[%d] != UINT32_MAX && ids[%d] >= (1u << 16)) err_fail("phase111: effect CID out of range");\n' % (slot, slot)]
    # Require direct value constructors only when a provider has an active row.
    # Runtime helper constructors are authenticated by the core descriptor bind.
    for row in rows:
        row_effects = {r['name'] for r in row['registrations']}
        active = ' || '.join('ids[%d] != UINT32_MAX' % slots[n] for n in sorted(row_effects))
        deps = sorted(set(row['cidNames']) - row_effects)
        if deps:
            missing = ' || '.join('ids[%d] == UINT32_MAX' % slots[n] for n in deps)
            parts.append('  if ((%s) && (%s)) err_fail("phase111: active provider lacks value CID");\n' % (active, missing))
    parts += ['  for (uint32_t i = 0; i < %du; ++i) {\n' % len(all_names),
              '    for (uint32_t j = 0; j < i; ++j)\n',
              '      if (ids[i] != UINT32_MAX && ids[i] == ids[j]) err_fail("phase111: semantic CID alias");\n',
              '  }\n']
    for effect in effects:
        slot = slots[effect['name']]
        parts.append('  if (ids[%d] != UINT32_MAX && io_eff_rows[ids[%d]].run != NULL) err_fail("phase111: duplicate effect row");\n' % (slot, slot))
    parts += ['  for (uint32_t i = 0; i < %du; ++i) p111_effect_cids[i] = ids[i];\n' % len(all_names)]
    parts += ['  %s();\n' % name for name in starts]
    parts += ['  p111_effects_bound = 1;\n}\n']
    generated = ''.join(parts)
    catalogue = dict(kind='phase111-effect-provider-catalogue', complete=True, targetsRun=False,
        profile=profile, selection=pin(selection_path), admission=pin(admission_path),
        selectedRuntime=assets['runtime'], selectedBase=assets['base'],
        selectedProviders=[describe(p, names) for p in selected],
        upstreamBaseProviders=[describe(p, names) for p in raw], hostProvider=describe(host, names),
        includedProviders=rows, semanticCidSlots=slots, registeredEffects=effects,
        boundary='Selected compatible native assets are authoritative; upstream Base catalogue is not substituted. Custom foreign C requires an explicit provider capability. No compiler/native execution by this preparer.')
    out.mkdir(parents=True, exist_ok=False)
    (out / 'providers.inc.c').write_text(generated)
    (out / 'catalogue.json').write_text(json.dumps(catalogue, indent=2) + '\n')
    manifest = dict(kind='phase111-cached-effects-source', complete=True, targetsRun=False,
        profile=profile, inputs=[pin(__file__), pin(selection_path), pin(admission_path),
                               assets['base'], assets['runtime'], *[pin(p) for p in providers]],
        providers=pin(out / 'providers.inc.c'), catalogue=pin(out / 'catalogue.json'),
        effectCount=len(effects), providerCount=len(providers),
        coreHelperCidDependencies=['SCon', 'SNil', 'Tuple', 'Done', 'Fail'],
        call='p111_effects_bind(lookup, context) after descriptor IDs are installed, before main CLI/effects; exactly once',
        scope='Source preparation only. Original provider bodies retained except semantic CID references and deferred guarded registration.')
    (out / 'manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    print(json.dumps(dict(complete=True, targetsRun=False, out=str(out), effects=len(effects), providers=len(providers))))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', type=Path, required=True)
    parser.add_argument('--profile', choices=['compiler', 'selected-base'], default='selected-base')
    args = parser.parse_args()
    prepare(args.out.resolve(), args.profile)
