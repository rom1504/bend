for(const p of files)same(pin(stage+'/'+p.file),p);
save(release+'/receipt.json',{kind:'phase103-native-cli-package',version:1,complete:true,scope,targetExecutions:0,method,host,archive:pin(archive),files,records:retained,qualification:{inputs:inputsPin,native:nativePin,controls:controlsPin,equivalence:equivalencePin},packaging:{tar,gzip,argv,staging:stage}});
console.log(JSON.stringify({complete:true,receipt:pin(release+'/receipt.json'),archive:pin(archive),files:files.length}));
